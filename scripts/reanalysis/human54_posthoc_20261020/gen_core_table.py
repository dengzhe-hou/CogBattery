"""Main-text Table 2: one key endpoint per paradigm, all models vs gate passers vs >=27B.

Reads saved outputs only (layer-one endpoints, section E gates, parameter table).
Family-bootstrap intervals use the frozen cluster_mean (seed 20261018, 5,000 draws,
human mean fixed), so the all-model column reproduces the paper's existing values.
"""
from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np
import pandas as pd

from scripts.reanalysis.human54_layers_20261019.analysis_statistics import cluster_mean

ROOT = Path(__file__).resolve().parents[3]
LAYER1 = ROOT / 'results/reanalysis/human54_layers_20261019/layer1'
GATES = ROOT / 'results/reanalysis/human54_posthoc_20261020_gates'
ROWS = [
    ('DS', 'digit_span', 'forward_minus_backward', 'Forward $-$ backward'),
    ('NB', 'n_back', 'load_2_control', '2-back control false alarms'),
    ('OS', 'operation_span', 'position_accuracy', 'Letter-position accuracy'),
    ('ST', 'stroop', 'error_interference', 'Error interference'),
    ('FL', 'flanker', 'error_interference', 'Error interference'),
    ('GN', 'go_nogo', 'false_alarm_rate', 'No-go false alarms'),
    ('CVLT', 'cvlt_word_list', 'learning_slope', 'Learning slope (words)'),
    ('DRM', 'drm_false_memory', 'no_warning|native', 'New $-$ lure false alarms'),
    ('SM', 'source_monitoring', 'direct_minus_indirect', 'Direct $-$ indirect accuracy'),
    ('FB', 'false_belief', 'session|FB_accuracy', 'False-belief accuracy'),
    ('EP', 'epitome_tom', 'mental_level_slope', 'Mental-state slope'),
    ('CAL', 'confidence_calibration', 'type2_auc_fixed_direction', 'Type-2 AUROC'),
    ('WAG', 'post_decision_wagering', 'high_wager_rate', 'Constant wager (models)'),
]


def fmt(x, digits=3):
    s = f'{x:.{digits}f}'
    return s.replace('-', '$-$') if x < 0 else s


def interval(stats):
    return f"{fmt(stats['mean'])} [{fmt(stats['lower'])}, {fmt(stats['upper'])}]"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, required=True)
    a = parser.parse_args()
    paired = pd.read_csv(LAYER1 / 'model_human_endpoints.csv', low_memory=False)
    paired = paired[(paired.rule == 'valid_only') & (paired.human_cohort == 'primary') & (paired.included == True)]
    e = pd.read_csv(LAYER1 / 'endpoints.csv', low_memory=False)
    e = e[(e.rule == 'valid_only') & (e.included == True)]
    gates = pd.read_csv(GATES / 'gates.csv').set_index(['model', 'task']).passed
    params = pd.read_csv(GATES / 'model_parameters.csv', index_col='model').params_b
    fam = pd.read_csv(ROOT / 'results/reanalysis/human54_layers_20261019/coverage/models.csv', index_col='model').family_merged
    lines = []
    for code, task, endpoint, label in ROWS:
        if code == 'WAG':
            v = e[(e.task == task) & (e.endpoint == endpoint)].set_index('model').value.astype(float)
            const = np.isin(v.to_numpy(), (0., 1.))
            g = np.array([bool(gates[(m, task)]) for m in v.index])
            big = np.array([params[m] >= 27 for m in v.index])
            lines.append(f'{code} & {label} & -- & {const.sum()}/{len(v)} & -- & {const[g].sum()}/{g.sum()} & {const[big].sum()}/{big.sum()} \\\\')
            continue
        s = paired[(paired.task == task) & (paired.endpoint == endpoint)].set_index('model')
        human = float(s.human_mean.iloc[0])
        x = s.value.astype(float)
        all_stats, _ = cluster_mean(x.to_numpy() - human, [fam[m] for m in x.index])
        g = [m for m in x.index if gates[(m, task)]]
        g_stats, _ = cluster_mean(x[g].to_numpy() - human, [fam[m] for m in g])
        big = [m for m in x.index if params[m] >= 27]
        sign = np.sign(all_stats['mean'])
        same = int(np.sum(np.sign(x[big].to_numpy() - human) == sign))
        lines.append(f"{code} & {label} & {fmt(human)} & {fmt(float(x.mean()))} & {interval(all_stats)} & "
                     f"{interval(g_stats)} ({len(g)}) & {fmt(float((x[big] - human).mean()))} ({same}/{len(big)}) \\\\")
    body = '\n'.join(lines)
    tex = rf"""\begin{{table*}}[t]
% Generated by scripts/reanalysis/human54_posthoc_20261020/gen_core_table.py from saved results.
\centering
\fontsize{{8.5}}{{9.6}}\selectfont
\setlength{{\tabcolsep}}{{2.2pt}}
\begin{{tabular}}{{@{{}}llrrlll@{{}}}}
\toprule
 & & & & \multicolumn{{2}}{{c}}{{Model $-$ human [95\%]}} & $\geq$27B models \\
\cmidrule(lr){{5-6}}\cmidrule(l){{7-7}}
Task & Key endpoint & Human & Model & All models & Gate passers ($n$) & Gap (same sign) \\
\midrule
{body}
\bottomrule
\end{{tabular}}
\caption{{One key behavioral endpoint per paradigm. Model means weight eligible models equally; intervals resample whole model families 5,000 times with the human mean fixed. Minimal-performance gates (Section~\ref{{sec:h54_gates}}) require above-chance accuracy (one-sided binomial: FL and ST congruent trials, EP control order 1, and overall SM, CAL, and WAG accuracy), hits above false alarms (one-sided Fisher: NB 2-back, GN, unwarned DRM), or at least half correct (DS and OS length 3, CVLT trial 1, FB true-belief items, where .5 equals two-location chance). Gates and endpoints share trials for DS, NB, OS, ST, FL, GN, CVLT, DRM, and SM; congruent ST and FL trials can also be passed by reading the word or flankers. The $\geq$27B column (nine models, six families, no native-thinking model) gives the mean gap without an interval and how many of the nine differ from humans in the all-model direction. For WAG, cells count models that always place the same wager; no human proportion exists. Table~\ref{{tab:h54_behavior_native}} summarizes all 13 paradigms; the release will give all 134 source-paired endpoints.}}
\label{{tab:h54_behavior_core}}
\end{{table*}}
"""
    a.output.write_text(tex)
    print(tex)


if __name__ == '__main__':
    main()
